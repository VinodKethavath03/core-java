package com.java_DataTypes;

public class PrimitiveDataTypes {
	byte b;
	short s;
	long l;
	int i;
	
	float f;
	double d;
	
	char c;
	boolean boo;
	
	

	public static void main(String[] args) {
		System.out.println("main method started");
		PrimitiveDataTypes t =new PrimitiveDataTypes();
		System.out.println("byte:"+t.b);//0
		System.out.println("short:"+t.s);//0
		System.out.println("long:"+t.l);//0
		System.out.println("int:"+t.i);//0
		
		System.out.println("float:"+t.f);//0.0
		System.out.println("double:"+t.d);//0.0
		
		System.out.println("char:"+t.c);
		System.out.println("boolean:"+t.boo);//false
		
		System.out.println("main method ended");
		
		

	}

}
